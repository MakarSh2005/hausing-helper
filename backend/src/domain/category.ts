import type { RequestCategory } from './enums.js';

/**
 * Категория заявки по ключевым словам, без LLM (ТЗ, этап 5).
 * Правила идут от специфичных к общим: «свет в подъезде» — это освещение, а не электричество;
 * «течёт с крыши» — кровля, а не водоснабжение. Если ни одно правило не сработало — null,
 * и бот предлагает выбрать категорию кнопками.
 */

// Кириллица: \b и \w в JS её не видят — используем [а-яa-z0-9] и явные просмотры.
const RULES: Array<[RequestCategory, RegExp[]]> = [
  ['gas', [/газ(?!он|ет)/, /пахнет газ/, /утечк[аи] газ/]],
  ['lighting', [/(свет|лампочк|лампа|освещен|темно).{0,30}(подъезд|лестниц|площадк|этаж|тамбур|коридор)/, /(подъезд|лестниц|площадк|тамбур|коридор).{0,30}(свет|лампочк|лампа|освещен|темно)/]],
  ['sewerage', [/засор/, /забил[аио]?с[ья]/, /канализац/, /не уходит вод/, /унитаз/, /(вода|воды) не уход/, /воняет из (слива|раковин|ванн|трап)/, /подвал.{0,20}(затоп|вод)/]],
  ['elevator', [/лифт/, /подъемник/]],
  ['roof', [/крыш/, /кровл/, /чердак/, /сосульк/, /(течет|капает|протека[а-яa-z0-9]*).{0,25}(с крыш|сверху на последн|потолок на последн)/, /последн[а-яa-z0-9]* этаж.{0,40}(теч|капа|протека|мокр)/]],
  ['heating', [/батаре/, /отоплен/, /радиатор/, /(холодно|холодные|холодная) (в квартир|в комнат|батаре|дома)/, /не греет/, /не топят/, /полотенцесушител/]],
  ['water', [/нет (горяч|холодн)[а-яa-z0-9]* вод/, /(горяч|холодн)[а-яa-z0-9]* вод[а-яa-z0-9]* (нет|не идет|отключ)/, /напор/, /кран/, /водопровод/, /(прорвал|лопнул|течет|течь|протека[а-яa-z0-9]*|капает).{0,25}(труб|стояк|вод)/, /(труб|стояк).{0,25}(прорвал|лопнул|течет|течь|протека|капает)/, /затопил/, /топят соседи/, /ржав[а-яa-z0-9]* вод/, /вода (ржав|мутн|грязн)/, /течет с потолк/, /протека[а-яa-z0-9]* потол/]],
  ['electricity', [/электри/, /нет свет/, /пропал свет/, /выбива[а-яa-z0-9]* (пробк|автомат)/, /щит(ок|ке|ка)/, /искрит/, /розетк/, /напряжени/]],
  ['garbage', [/мусор[а-яa-z0-9]* (не выв|не забира|переполн|вывоз)/, /(не вывоз|не вывезл|не забирают).{0,20}мусор/, /(мусорн|контейнер|бак)[а-яa-z0-9]*.{0,20}(переполн|полн|не выв)/, /помойк/, /(?<![а-яa-z0-9])тко(?![а-яa-z0-9])/, /мусоропровод/]],
  ['entrance', [/подъезд[а-яa-z0-9]*.{0,30}(двер|окн|стекл|грязн|уборк|не убира|мусор)/, /(двер|окн|стекл|грязн|уборк|не убира).{0,30}подъезд/, /домофон/, /разбит[а-яa-z0-9]* (окн|стекл)/, /входн[а-яa-z0-9]* двер/]],
  ['yard', [/двор/, /снег/, /налед/, /гололед/, /детск[а-яa-z0-9]* площадк/, /газон/, /дерев/, /лавочк/, /скамейк/, /ям[аы]/, /парковк/, /тротуар/]],
];

export function detectCategory(text: string): RequestCategory | null {
  const t = text.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
  for (const [category, patterns] of RULES) {
    if (patterns.some((re) => re.test(t))) return category;
  }
  return null;
}
